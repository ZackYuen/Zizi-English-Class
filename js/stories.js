(function attachStoriesToVocab() {
    var list = window.D;
    var stories = window.WORD_STORIES;
    if (!list || !stories) return;
    for (var i = 0; i < list.length; i++) {
        var s = stories[list[i].w];
        if (s) {
            var nick = s.nick || (window.WORD_NICKS && window.WORD_NICKS[list[i].w]) || s.yue;
            s.nick = nick;
            list[i].yue = s.yue;
            list[i].nick = nick;
            list[i].story = s.story;
            list[i].parts = s.parts;
            list[i].from = s.from;
        }
    }
})();
